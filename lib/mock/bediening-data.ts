/** Duur in ure, soos die gegenereerde `ure`-kolom in Postgres dit bereken. */
function ure(begin: string | null, eind: string | null): number | null {
  if (!begin || !eind) return null;
  const [bu, bm] = begin.split(":").map(Number);
  const [eu, em] = eind.split(":").map(Number);
  return Math.round(((eu * 60 + em - (bu * 60 + bm)) / 60) * 100) / 100;
}

